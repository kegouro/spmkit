def test_clean_hertz_family_recovery() -> None:
    """Clean hertz-family phantoms recover E within a few percent; the
    residual bias is the FS-F1 contact precision (~1 sample = 1.5e-8 m)."""
    cases = generate_phantoms()
    fits = {
        "M01": (fit_hertz_sphere, {"tip_radius": 1e-6}),
        "M02": (fit_sneddon_cone, {"half_angle": math.radians(20.0)}),
        "M03": (fit_flat_punch, {"punch_radius": 1e-6}),
        "M09": (fit_hertz_sphere, {"tip_radius": 1e-6}),
        "M12": (fit_hertz_sphere, {"tip_radius": 1e-6}),
    }
    for cid, (fn, kwargs) in fits.items():
        prepared = _prepared(cases[cid])
        ind = compute_indentation(prepared)
        window = select_contact_fit_window(prepared, ind, min_indentation=0.0,
                                           min_points=10)
        fit = fn(prepared, ind, window, **kwargs)
        assert fit.success, cid
        rel = abs(fit.parameters["E"] - 5e3) / 5e3
        assert rel < 0.05, (cid, rel)


