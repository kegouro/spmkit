@pytest.mark.skipif(
    not NANITE_DIR.exists(),
    reason="evidencia externa (nanite) no disponible (gitignored)",
)
def test_external_nanite_contact_overlap() -> None:
    """The FS-F1 contact ensemble lands inside the nanite 4-method contact
    bracket on the shared P-case campaign (checked-in black-box outputs)."""
    campaign_input = NANITE_DIR / "campaign_input.json"
    campaign_output = NANITE_DIR / "campaign_output.json"
    assert campaign_input.exists() and campaign_output.exists()
    inp = json.loads(campaign_input.read_text())
    out = json.loads(campaign_output.read_text())
    by_id = {o["case_id"]: o for o in out}
    inside = 0
    prepared_count = 0
    for case in inp["cases"]:
        cid = case["case_id"]
        o = by_id[cid]
        nanite = [v for k, v in o.items() if k.startswith("contact_") and isinstance(v, int)]
        assert nanite, cid
        curve = _curve_from_phantom_arrays(
            np.asarray(case["approach_height"]), np.asarray(case["approach_force"]),
            np.asarray(case["retract_height"]), np.asarray(case["retract_force"]),
            case["spring_constant"],
        )
        try:
            prepared = prepare_force_curve(curve)
        except ForceFoundationError:
            continue  # witness: some P-cases fail preparation typed
        prepared_count += 1
        f1 = prepared.contact.selected.index
        if min(nanite) <= f1 <= max(nanite):
            inside += 1
    assert prepared_count >= 15, prepared_count
    assert inside == prepared_count, f"{inside}/{prepared_count}"


