def test_adhesive_recovery_trimmed_windows() -> None:
    """DMT/JKR recovery on snap-in curves, with windows trimmed past the
    snap-in region.  The FS-F1 contact ensemble lands up to ~10 samples off
    on snap-in curves; the honest recovery bounds are documented here."""
    cases = generate_phantoms()
    prepared = _prepared(cases["M04"])
    ind = compute_indentation(prepared)
    window = select_contact_fit_window(prepared, ind, min_indentation=1.8e-7,
                                       min_points=10)
