def test_real_data_no_silent_garbage() -> None:
    """On the real NID spectroscopy set every curve either completes the
    FS-F2 stack or raises a typed failure; a successful fit must be finite."""
    from spmkit.core.io import load_force

    nid_path = (
        Path(__file__).resolve().parent / "fixtures" / "force_foundation" / "spectroscopy.nid"
    )
    assert nid_path.exists()
    vol = load_force(str(nid_path))
    completed = 0
    fitted = 0
    typed = 0
    for i in range(vol.n_curves):
        curve = vol.curve(i)
        ext = curve.extend
        if ext is None:
            continue
        z = np.asarray(ext.raw_height, dtype=np.float64)
        if not (z.size and np.all(np.diff(z) > 0)):
            continue
        try:
            prepared = prepare_force_curve(curve)
            completed += 1
            ind = compute_indentation(prepared)
            window = select_contact_fit_window(prepared, ind, min_points=10)
            fit = fit_hertz_sphere(prepared, ind, window, tip_radius=10e-9)
            assert fit.success
            assert np.isfinite(fit.parameters["E"])
            assert np.isfinite(fit.objective)
            fitted += 1
        except (ForceMechanicsError, ForceFoundationError):
            typed += 1
    assert completed + typed >= 1
    assert fitted >= 0
